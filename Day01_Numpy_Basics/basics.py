import numpy as np

numbers = np.array([10,20,30,40,50])

print('Array:')
print(numbers)

print('\nType')
print(type(numbers))

print('\nNumber of dimensions:')
print(numbers.ndim)

print('\nShape:')
print(numbers.shape)

print('\nTotal elements:')
print(numbers.size)

print('\nData type')
print(numbers.dtype)
