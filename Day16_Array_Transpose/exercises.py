import numpy as np

numbers = np.array([
    [1, 2, 3],
    [4, 5, 6]
])

# Exercise 1: Print the original array.
print("Original array:")
print(numbers)

# Exercise 2: Print the transposed array.
print("Transposed array:")
print(numbers.T)

# Exercise 3: Print the original shape.
print("Original shape:")
print(numbers.shape)

# Exercise 4: Print the transposed shape.
print("Transposed shape:")
print(numbers.T.shape)